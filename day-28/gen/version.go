//go:build ignore

// gen/version.go is a standalone generator invoked by:
//
//	go generate ./...
//
// It writes internal/version/version.go containing a BuildTime constant
// set to the current UTC time in RFC3339 format.
//
// The //go:build ignore tag ensures this file is never compiled as part
// of the main package — it is only executed when go generate runs it.

package main

import (
	"fmt"
	"os"
	"time"
)

func main() {
	const dst = "internal/version/version.go"

	if err := os.MkdirAll("internal/version", 0o755); err != nil {
		fmt.Fprintln(os.Stderr, "mkdir:", err)
		os.Exit(1)
	}

	content := fmt.Sprintf(`// Code generated by gen/version.go; DO NOT EDIT.

package version

// BuildTime is the UTC timestamp from the last "go generate" run.
// Refresh with: go generate ./...
const BuildTime = %q
`, time.Now().UTC().Format(time.RFC3339))

	if err := os.WriteFile(dst, []byte(content), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "write:", err)
		os.Exit(1)
	}

	fmt.Println("generated", dst)
}
